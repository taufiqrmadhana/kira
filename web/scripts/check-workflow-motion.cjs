// Browser motion checks use read-only scratch fixtures; every write is intercepted.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=process.env.KIRA_E2E_BASE||'http://127.0.0.1:5173';
const screenshots=path.resolve(__dirname,'../../docs/screens/dev2');
const read=async endpoint=>{const response=await fetch(`http://127.0.0.1:8000/api${endpoint}`,{headers:{'X-Kira-Client':'zestly-demo'}});assert(response.ok);return response.json();};
const json=(route,value)=>route.fulfill({contentType:'application/json',body:JSON.stringify(value)});
(async()=>{
  const [source,status]=await Promise.all([read('/workflow?rows=5'),read('/status')]);
  const browser=await chromium.launch({headless:true});
  const errors=[];fs.mkdirSync(screenshots,{recursive:true});
  try{for(const reduced of [false,true]){
    const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:reduced?'reduce':'no-preference'});
    const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
    page.setDefaultTimeout(10000);
    const workflow=structuredClone(source);
    const rec={id:'pos.branch',table:'pos',column:'branch',kind:'map',title:'Standardize outlet names',why:'Browser acceptance fixture',decision:null,choices:['Menteng'],items:[{from:'MTG',to:'Menteng',rows:1}]};
    workflow.cleaning.recommendations=[rec];
    workflow.status.cleaning.open=1;
    await context.route('**/api/workflow?*',route=>json(route,workflow));
    await context.route('**/api/tables/clean/pos?*',route=>json(route,{columns:[{name:'branch',type:'text'}],rows:[{branch:'Menteng',__was:{branch:'MTG'}}],total:1,changed:1,dropped:0}));
    await context.route('**/api/cleaning/recommendations/pos.branch',route=>{rec.decision='accept';workflow.status.cleaning.open=0;return json(route,rec);});
    await context.route('**/api/cleaning/save',route=>{workflow.cleaning.recommendations=[];return json(route,workflow.cleaning.rules);});
    let releaseUpload,releaseConvert,releaseMatching;
    await context.route('**/api/files/pos',async route=>{assert.equal(route.request().method(),'POST');await new Promise(resolve=>{releaseUpload=resolve;});workflow.files.push({...workflow.files[0],id:99999,type:'pos',name:'motion-upload.csv',folder:'',wrong_area:true,looks_like:'bank'});workflow.status.files.pos++;await json(route,[{name:'motion-upload.csv',status:'added',ids:[99999]}]);});
    await context.route('**/api/convert',async route=>{await new Promise(resolve=>{releaseConvert=resolve;});await json(route,workflow.conversion);});
    await context.route('**/api/matching/l1/run',async route=>{await new Promise(resolve=>{releaseMatching=resolve;});await json(route,status.matching.l1.summary);});
    const animations=selector=>page.locator(selector).first().evaluate(element=>element.getAnimations({subtree:true}).filter(animation=>animation.playState==='running').length);
    const style=(selector,property)=>page.locator(selector).first().evaluate((element,property)=>getComputedStyle(element).getPropertyValue(property),property);
    await page.goto(base+'/workflow?step=1&c=zestly-demo',{waitUntil:'domcontentloaded'});
    await page.locator('.workflow[data-ready=true]').waitFor();
    assert.equal(await style('.wf-step-indicator','transition-duration'),reduced?'0s':'0.45s, 0.45s, 0.45s');
    assert.equal(await style('.wf-step-number .lucide-check','animation-name'),reduced?'none':'wf-check-draw');
    assert.equal(await style('.wf-dropzone','transition-duration'),reduced?'0s':'0.15s, 0.15s');
    await page.getByLabel('Drop POS files or folders').evaluate(element=>element.dispatchEvent(new DragEvent('dragover',{bubbles:true,dataTransfer:new DataTransfer()})));
    assert(await page.locator('.wf-dropzone.dragging').count());
    await page.getByLabel('POS files',{exact:true}).setInputFiles({name:'motion-upload.csv',mimeType:'text/csv',buffer:Buffer.from('branch,amount\nMTG,100')});
    await page.getByRole('progressbar',{name:'Upload motion-upload.csv'}).waitFor();
    // Intercepted requests send no bytes: keep progress indeterminate until completion.
    assert.equal(await page.getByRole('progressbar',{name:'Upload motion-upload.csv'}).getAttribute('value'),null);
    assert((await page.locator('.wf-upload-progress').textContent()).includes('Uploading'));
    for(let attempt=0;!releaseUpload&&attempt<100;attempt++)await new Promise(resolve=>setTimeout(resolve,10));
    assert(releaseUpload,'Upload request should reach the intercepted endpoint');
    releaseUpload();await page.locator('.wf-file-list').getByText('motion-upload.csv',{exact:true}).waitFor();
    assert.equal(await style('.wf-file-list li:has-text("motion-upload.csv")','animation-name'),reduced?'none':'wf-file-enter');
    assert.equal(await style('.wf-wrong-area','animation-name'),reduced?'none':'wf-line-enter');
    await page.getByRole('button',{name:'Next: Convert',exact:true}).click();
    await page.getByRole('heading',{name:'Convert raw files into tables',exact:true}).waitFor();
    if(reduced)assert.equal(await animations('.wf-step-indicator'),0);
    else assert(await animations('.wf-step-indicator')>0,'Active step segment should slide');
    if(reduced)assert.equal(await animations('.wf-step-transition'),0);
    else assert(await animations('.wf-step-transition')>0,'Step panel should move in the direction of travel');
    await page.getByRole('button',{name:'Convert again',exact:true}).click();
    await page.getByText('Reading the uploaded files and preparing their columns.',{exact:false}).waitFor();
    assert.equal(await page.locator('.wf-flow-dot').count(),reduced?0:9);
    assert.equal(await style('.is-scanning .wf-convert-source li','animation-name'),reduced?'none':'wf-source-dim');
    await page.screenshot({path:path.join(screenshots,`motion-convert-${reduced?'reduced':'active'}.png`),timeout:10000});
    releaseConvert();await page.getByRole('button',{name:'Convert again',exact:true}).waitFor();
    assert.equal(await page.locator('.wf-flow-dot').count(),0);
    assert.equal(await style('.wf-convert-reveal','animation-name'),reduced?'none':'wf-convert-enter');
    assert.equal(await style('.wf-convert-state.is-complete .lucide-check','animation-name'),reduced?'none':'wf-check-pop');
    await page.getByRole('button',{name:'Next: Clean',exact:true}).click();
    await page.getByRole('button',{name:'Accept Standardize outlet names'}).click();
    await page.locator('.wf-clean-saved').getByRole('button',{name:'Undo Standardize outlet names'}).waitFor();
    assert.equal(await style('.wf-clean-decision .wf-rec-fields','transition-duration'),reduced?'0s':'0.22s, 0.22s');
    assert.equal(await page.locator('.wf-clean-saved select:visible').count(),0);
    await page.getByRole('button',{name:/Save cleaning rules v/}).click();
    await page.locator('.wf-clean-flash').waitFor();
    assert.equal(await style('.wf-clean-flash td:has(.wf-changed-cell)','animation-name'),reduced?'none':'wf-clean-flash');
    await page.getByRole('button',{name:'Next: Run matching',exact:true}).click();
    await page.locator('.step4[data-ready=true]').waitFor();
    await page.getByRole('region',{name:'POS to settlement',exact:true}).getByRole('button',{name:'Run matching',exact:true}).click();
    await page.getByRole('group',{name:'Matching flow'}).getByRole('status').waitFor();
    assert.equal(await page.locator('.wf-flow-dot').count(),reduced?0:3);
    assert.equal(await page.getByRole('group',{name:'Matching flow'}).getByRole('progressbar').count(),0);
    await page.getByRole('group',{name:'Matching flow'}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(screenshots,`motion-matching-${reduced?'reduced':'active'}.png`),timeout:10000});
    releaseMatching();await page.getByText(/POS to settlement complete:/).waitFor();
    assert.equal(await page.locator('.wf-flow-dot').count(),0);
    assert.equal(await style('.step4-completed','animation-name'),reduced?'none':'wf-line-enter');
    assert.equal(await style('.step4-rule-hits[data-new=true]','animation-name'),reduced?'none':'wf-rule-hit');
    if(reduced){const expected=(await read('/matching/results')).totals;assert.equal(parseFloat(await page.locator('.step4-ring-value').getAttribute('stroke-dasharray')),expected.full/expected.pos*100);}
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    console.log(`PASS workflow catalogue 2–7: ${reduced?'reduced motion, instant final state':'motion enabled, real pending state and final result'}`);
    await context.close();
  }assert.deepEqual(errors,[]);}finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
